:- initialization(main, main).

main :-
    source_file(main, RunnerFile),
    file_directory_name(RunnerFile, Directory),
    directory_file_path(Directory, 'ir_tests.pl', Tests),
    load_files(Tests, [silent(true)]),
    directory_file_path(Directory, 'proof_checker_tests.pl', ProofTests),
    load_files(ProofTests, [silent(true)]),
    directory_file_path(Directory, 'test_corpus.pl', CorpusTests),
    load_files(CorpusTests, [silent(true)]),
    directory_file_path(Directory, 'runner_tests.pl', RunnerTests),
    load_files(RunnerTests, [silent(true)]),
    directory_file_path(Directory, 'pid_tests.pl', PidTests),
    load_files(PidTests, [silent(true)]),
    directory_file_path(Directory, 'loop2_tests.pl', Loop2Tests),
    load_files(Loop2Tests, [silent(true)]),
    directory_file_path(Directory, 'detlog_tests.pl', DetlogTests),
    load_files(DetlogTests, [silent(true)]),
    directory_file_path(Directory, 'detlog_transform_tests.pl',
                        DetlogTransformTests),
    load_files(DetlogTransformTests, [silent(true)]),
    directory_file_path(Directory, 'plop_tests.pl', PlopTests),
    load_files(PlopTests, [silent(true)]),
    directory_file_path(Directory, 'algebraplop_tests.pl', AlgebraPLOpTests),
    load_files(AlgebraPLOpTests, [silent(true)]),
    directory_file_path(Directory, 's2a_tests.pl', S2ATests),
    load_files(S2ATests, [silent(true)]),
    run_tests,
    halt.
